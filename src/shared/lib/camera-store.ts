// Камера, заданная в самой сцене (пустышки «Камера» и «Цель камеры» из Блендера), и объект съёмки.
// Модель пишет сюда мировые координаты после обновления анимации, камера сайта читает в том же кадре.
export const cameraStore = {
  active: false,
  cx: 0, cy: 0, cz: 0,       // где камера
  tx: 0, ty: 0, tz: 0,       // куда смотрит
  sx: 0, sy: 0, sz: 0,       // объект съёмки — для узких экранов кадр строится вокруг него
};

export function resetCameraStore(): void {
  Object.assign(cameraStore, { active: false, cx: 0, cy: 0, cz: 0, tx: 0, ty: 0, tz: 0, sx: 0, sy: 0, sz: 0 });
}
